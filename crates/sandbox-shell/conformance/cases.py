"""Conformance cases for the sandbox shell (PLAN.md §4.4, §7, §9 M1).

Each case is a script that runs unchanged under GNU bash and under the sandbox
shell. Scripts use relative paths only and never print the working directory,
because bash runs in a host directory and the sandbox starts at `/`.

`record.py` runs every case under bash and writes `cases.json`, which the Rust
test replays. Expected output is therefore recorded from bash, never written by
hand.
"""

