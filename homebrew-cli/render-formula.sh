#!/usr/bin/env bash
# Writes the Homebrew formula for one release of the sandbox CLI.
#
# Usage: homebrew-cli/render-formula.sh <version> [output]
#
# The formula points at the raw binaries that the release-binaries workflow
# attaches to the GitHub release v<version>. The script downloads each of the
# four Unix binaries and records its SHA-256 digest, so a digest is never typed
# by hand. Windows has no Homebrew formula and is left out.
set -euo pipefail

version="${1:?usage: homebrew-cli/render-formula.sh <version> [output]}"
out="${2:-$(cd "$(dirname "$0")" && pwd)/Formula/sandbox.rb}"

base="https://github.com/frontal-labs/sandbox/releases/download/v${version}"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

digest() {
  local target="$1"
  curl -fsSL -o "$tmp/sandbox-$target" "$base/sandbox-$target"
  shasum -a 256 "$tmp/sandbox-$target" | cut -d' ' -f1
}

sha_darwin_arm64="$(digest aarch64-apple-darwin)"
sha_darwin_x64="$(digest x86_64-apple-darwin)"
sha_linux_arm64="$(digest aarch64-unknown-linux-gnu)"
sha_linux_x64="$(digest x86_64-unknown-linux-gnu)"

mkdir -p "$(dirname "$out")"
cat > "$out" <<EOF
# typed: strict
# frozen_string_literal: true

# Generated by homebrew-cli/render-formula.sh for v${version}.
# Do not edit by hand. Render it again for the next release.
class Sandbox < Formula
  desc "Command-line client for Frontal Sandbox"
  homepage "https://github.com/frontal-labs/sandbox"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "${base}/sandbox-aarch64-apple-darwin", using: :nounzip
      sha256 "${sha_darwin_arm64}"
    end
    on_intel do
      url "${base}/sandbox-x86_64-apple-darwin", using: :nounzip
      sha256 "${sha_darwin_x64}"
    end
  end

  on_linux do
    on_arm do
      url "${base}/sandbox-aarch64-unknown-linux-gnu", using: :nounzip
      sha256 "${sha_linux_arm64}"
    end
    on_intel do
      url "${base}/sandbox-x86_64-unknown-linux-gnu", using: :nounzip
      sha256 "${sha_linux_x64}"
    end
  end

  def install
    # Each download is one bare binary, saved under its release name.
    bin.install Dir["sandbox-*"].first => "sandbox"
  end

  test do
    assert_match "sandbox", shell_output("#{bin}/sandbox --help")
  end
end
EOF

echo "wrote $out for v${version}"
